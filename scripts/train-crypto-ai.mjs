// Uses existing public-market research cache; never reads real account history.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {aiFeatures,newShadow,settleShadow,predictR,shadowStats,AI_STEP,AI_HORIZON} from '../crypto-ai.js';
import {fitRidge} from '../crypto-ai-fit.js';
const root=new URL('../.matning/crypto/',import.meta.url);
const read=name=>readFileSync(new URL(name,root),'utf8');
const hash=s=>createHash('sha256').update(s).digest('hex');
let raw;
try{raw=read('results.json');}catch{throw Error('Missing .matning/crypto/results.json and symbol candle caches. See CRYPTO-AI.md. No model was written.');}
const archive=JSON.parse(raw);
const trades=archive.books.filter(b=>b.variant==='current'&&b.size==='risk1'&&b.slip===.0005).flatMap(b=>b.trades);
const symbols=[...new Set(trades.map(t=>t.symbol))].sort();
const hashes={},data={};
for(const symbol of symbols){
  const text=read(symbol+'.json'),d=JSON.parse(text);hashes[symbol]=hash(text);
  if(d.category!=='spot')throw Error('Expected spot candles');
  d.bars.forEach((b,i)=>{if(![b.t,b.o,b.h,b.l,b.c,b.v].every(Number.isFinite)||b.t%AI_STEP||b.v<0||
    Math.min(b.o,b.h,b.l,b.c)<=0||b.h<Math.max(b.o,b.c,b.l)||b.l>Math.min(b.o,b.c)||i&&b.t-d.bars[i-1].t!==AI_STEP)throw Error('Invalid '+symbol+' candle');});
  data[symbol]=d.bars;
}
// Fixed before fitting. This period was inspected in earlier strategy research;
// call it retrospective evaluation, never an untouched/prospective holdout.
const split=Date.parse('2026-07-12T00:00:00Z'),end=Date.parse('2026-09-10T00:00:00Z');
const samples=[];
for(const t of trades){
  const bars=data[t.symbol],i=(t.opened-bars[0].t)/AI_STEP;
  if(!Number.isInteger(i)||i<1000||!bars[i])continue;
  const dir=t.side==='long'?1:-1,px=t.entry/(1+dir*.0005);
  const signal={id:String(t.opened),inst:t.symbol,side:t.side,status:'ACTIVE',entry:px,sl:t.sl,tp:t.tp,oppnad:t.opened};
  // Only the opening quote and bars closed before this historical decision.
  const ctx={px,simulated:false,bars:bars.slice(Math.max(0,i-2000),i)};
  const f=aiFeatures(signal,ctx,t.opened);if(!f)continue;
  const hard=f.review.checks.filter(c=>['data','geometry','net','age','chase'].includes(c.key)).every(c=>c.ok);
  const row=newShadow(signal,ctx,t.opened,{selective:f.review.pass},'training');
  const done=settleShadow(row,bars.slice(i+1,i+2+AI_HORIZON/AI_STEP),t.opened+AI_HORIZON+2*AI_STEP);
  if(done.status==='closed'&&done.closed<end)samples.push({x:f.x,y:done.netR,at:t.opened,closed:done.closed,
    inst:t.symbol,selective:f.review.pass,hard});
}
const train=samples.filter(r=>r.at<split&&r.closed<split);
const test=samples.filter(r=>r.at>=split);
const fitted=fitRidge(train),threshold=.1;
const scored=test.map(r=>({...r,status:'closed',netR:r.y,accepted:r.hard&&predictR(fitted,r.x)>=threshold}));
const stats=shadowStats(scored);
const model={...fitted,version:'crypto-ridge-v1-'+hash(JSON.stringify(fitted)).slice(0,12),
  trainedAt:new Date().toISOString(),trainEnd:split,dataEnd:end,symbols,threshold,validated:false,
  training:{n:train.length,from:Math.min(...train.map(r=>r.at)),lastOutcome:Math.max(...train.map(r=>r.closed)),lambda:30},
  evaluation:{kind:'retrospective',from:split,to:end,stats},
  provenance:{archive:hash(raw),candles:hashes},
  limitations:['Previously inspected historical period','Only baseline portfolio candidates, not all signals',
    'Spot prices; no funding','Overlapping hypothetical outcomes, not account returns','Fixed 24h horizon; decision candle ignored']};
writeFileSync(new URL('../crypto-ai-model.js',import.meta.url),'// Generated by scripts/train-crypto-ai.mjs. Experimental; no trading authority.\nexport const CRYPTO_AI_MODEL = '+JSON.stringify(model,null,2)+';\n');
console.log(JSON.stringify({version:model.version,training:model.training,evaluation:model.evaluation},null,2));
